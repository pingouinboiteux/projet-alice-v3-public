def environment(home):
    keep = {'SYSTEMROOT', 'WINDIR', 'SYSTEMDRIVE', 'COMSPEC', 'PATH', 'PATHEXT',
            'USERPROFILE', 'LOCALAPPDATA', 'APPDATA', 'PROGRAMFILES', 'PROGRAMFILES(X86)',
            'PROGRAMDATA', 'USERNAME', 'USERDOMAIN', 'NUMBER_OF_PROCESSORS', 'PROCESSOR_ARCHITECTURE'}
    env = {k:v for k,v in os.environ.items() if k.upper() in keep}
    env['CODEX_HOME'] = str(home)
    env['CODEX_DISABLE_TELEMETRY'] = '1'
    env['TEMP'] = env['TMP'] = str(home / 'tmp')
    (home / 'tmp').mkdir(parents=True, exist_ok=True)
    env['PATH'] = str(ROOT / 'runtime/codex/path') + os.pathsep + env.get('PATH', '')
    return env


