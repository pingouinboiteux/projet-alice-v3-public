def inventory(folder):
    values = {}
    for directory, dirs, files in os.walk(folder, followlinks=False):
        for name in dirs + files:
            if (Path(directory) / name).lstat().st_file_attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT:
                raise ValueError('Lien de fichier refuse dans l atelier')
        dirs[:] = [d for d in dirs if d not in {'.git', '__pycache__'} and not
                   (Path(directory) / d).is_symlink()]
        for name in files:
            p = Path(directory) / name
            if p.is_symlink():
                continue
            size = p.stat().st_size
            if size > 10 * 1024**2:
                values[p.relative_to(folder).as_posix()] = {'bytes': size}
            else:
                values[p.relative_to(folder).as_posix()] = {'bytes': size,
                    'sha256': hashlib.sha256(p.read_bytes()).hexdigest()}
    return values


